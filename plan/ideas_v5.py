def build():
    out = [copy.deepcopy(d) for d in V4 if d["slug"] not in CUT]
    out += copy.deepcopy(NEW)
    for d in out:
        d["myinfo"] = d["slug"] in MYINFO
        d["facts"] = FACTS.get(d["slug"], [])
        if d["slug"] == "calorie-counter":
            d["b"]["helper"] = "nutrition.py looks foods up in a bundled FoodData Central download, so no API key ships in the browser and no request leaves the device."
    return out

IDEAS = build()
